#!/usr/bin/env python3
"""The repair effect round the ship's picture in the tunnel -> src/repair_art.s.

    python tools/repairgen.py SHIP_PNG X0,Y0 FRAME_STEM

SHIP_PNG is the ship's picture as it stands on the tunnel's BACKGROUND (the
Makefile's TUNSHIP_PNG, composed into tunnel_art.s by artgen.py), placed at
portrait (X0, Y0). FRAME_STEM names the animation: FRAME_STEM1.png,
FRAME_STEM2.png, ... as far as they go, each the same size as SHIP_PNG and drawn
over the same ship (the user's, assets/png/ship/ship_anim*.png).

THE SHIP IS ALREADY ON THE SCREEN - it is background, and costs no frame
anything - so a frame of the animation is only what it ADDS to it: the frame's
lit pixels that the background does not have. Those are cut out as ONE SPRITE A
FRAME, as narrow as the hardware allows: 8 framebuffer columns, one byte, no
overlay plane - the cheapest blit there is (MAD65_GPU_OS.md: spr_blit_8_noov).
In TATE the byte runs DOWN the player's screen, so a frame's sparks have to sit
within 8 portrait rows; one whose sparks span more gets the 16-column bucket, and
this says so. The sprite is OR-ed onto the image, which already holds the
background, so a frame that took a pixel AWAY from the ship cannot be shown -
that is an error here, not a silent difference.

WHAT IT EMITS (one .s, included by src/sprites.s straight behind the capsule's art):
  RP_FRAMES, RP_PAGES             the animation's size; RP_PAGE is sprites.s's
  RP_T<n>, RP_O<n>, RP_H<n>       frame n's TYPE, byte offset from RP_PAGE, HEIGHT
                                  - for the definition pages
  repair_data                     the art, in SPRART (bank 7), whole pages
  RP_XL, RP_YL                    in TUNCODE3 (bank 11, the lifepods' - bank 10 is
                                  full): frame n's top-left on the framebuffer
  RP_XH, RP_YH                    ...whose high bytes are one constant each (checked)
"""

import sys
from pathlib import Path

from PIL import Image

sys.path.insert(0, str(Path(__file__).resolve().parent))
from artgen import lit_png  # noqa: E402 - the one pixel convention
from sprgen import load_planes  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent
DST = ROOT / "src" / "repair_art.s"
MAX_PAGES = 8                           # GPU pages sprites.s gives it, from RP_PAGE


def main(ship, at, stem):
    x0, y0 = (int(v) for v in at.split(","))
    sw, sh, bg = lit_png(ship)
    names = []
    while Path(f"{stem}{len(names) + 1}.png").exists():
        names.append(Path(f"{stem}{len(names) + 1}.png"))
    if not names:
        sys.exit(f"no frames: {stem}1.png does not exist")

    blob, rows = bytearray(), []
    for n, src in enumerate(names):
        w, h, on = lit_png(src)
        if (w, h) != (sw, sh):
            sys.exit(f"{src}: {w}x{h}, but the ship's picture is {sw}x{sh}")
        gone = bg - on
        if gone:
            sys.exit(f"{src}: takes {len(gone)} pixel(s) away from the ship, e.g. {min(gone)} -"
                     " a sprite can only add")
        add = on - bg
        if not add:
            sys.exit(f"{src}: adds nothing to the ship")
        ax0, ax1 = min(x for x, _ in add), max(x for x, _ in add)
        ay0, ay1 = min(y for _, y in add), max(y for _, y in add)
        band = 8 if ay1 - ay0 < 8 else 16 if ay1 - ay0 < 16 else None
        if band is None:
            sys.exit(f"{src}: its sparks span {ay1 - ay0 + 1} rows - more than a 16-column sprite")
        strip = Image.new("RGBA", (ax1 - ax0 + 1, band), (0, 0, 0, 0))
        for x, y in add:
            strip.putpixel((x - ax0, y - ay0), (255, 255, 255, 255))
        sw_, sh_, type_byte, data, has_overlay, _ = load_planes(strip, True)
        assert sw_ == band and not has_overlay
        fbx = y0 + ay0                          # the byte's first column: portrait y
        fby = 299 - (x0 + ax1)                  # its first row: the strip's right edge
        rows.append((src.stem, type_byte, len(blob), sh_, fbx, fby, band, len(add)))
        blob += data
        if band != 8:
            print(f"{src.name}: sparks over {ay1 - ay0 + 1} rows - a 16-column sprite")

    pages = (len(blob) + 255) // 256
    if pages > MAX_PAGES:
        sys.exit(f"{len(blob)} bytes - more than the {MAX_PAGES} GPU pages sprites.s gives it")
    blob += bytes(pages * 256 - len(blob))
    xh = {r[4] >> 8 for r in rows}
    yh = {r[5] >> 8 for r in rows}
    if len(xh) != 1 or len(yh) != 1:
        sys.exit("the frames straddle a 256 boundary on the framebuffer - RP_XH/RP_YH would vary")

    out = [
        "; " + "=" * 75,
        f"; repair_art.s - GENERATED by tools/repairgen.py from {names[0].as_posix()}",
        f"; .. {names[-1].name} over {Path(ship).as_posix()} at portrait ({x0},{y0}). Do not edit.",
        "; " + "=" * 75,
        f"; The repair effect: {len(names)} frames, each only what it adds to the ship on the",
        "; background, one no-overlay sprite (--tate). Frame: WxH, offset, fb top-left, pixels.",
        "; " + "=" * 75,
        "",
    ]
    for name, t, off, ht, fbx, fby, band, npx in rows:
        out.append(f"; {name}: {band}x{ht}, offset {off}, fb ({fbx},{fby}), {npx} px")
    out += [
        "",
        f"RP_FRAMES   = {len(names)}             ; the animation, one sprite slot each",
        f"RP_PAGES    = {pages}              ; GPU pages, from RP_PAGE on",
        f"RP_XH       = {xh.pop()}              ; every frame's fb x high byte...",
        f"RP_YH       = {yh.pop()}              ; ...and fb y's",
    ]
    for n, (_, t, off, ht, *_r) in enumerate(rows):
        out.append(f"RP_T{n} = ${t:02X}")
        out.append(f"RP_O{n} = {off}")
        out.append(f"RP_H{n} = {ht}")
    out += ["", "        .pushseg", '        .segment "SPRART"', "        .align  256", "repair_data:"]
    for i in range(0, len(blob), 16):
        out.append("        .byte   " + ", ".join(f"${b:02X}" for b in blob[i:i + 16]))
    out += ['        .segment "TUNCODE3"', "RP_XL:"]
    for i in range(0, len(rows), 11):
        out.append("        .byte   " + ", ".join(str(r[4] & 255) for r in rows[i:i + 11]))
    out.append("RP_YL:")
    for i in range(0, len(rows), 11):
        out.append("        .byte   " + ", ".join(str(r[5] & 255) for r in rows[i:i + 11]))
    out += ["        .popseg", ""]
    DST.write_text("\n".join(out), newline="\n")
    print(f"{len(blob)} bytes, {len(names)} frame(s), {pages} page(s) -> "
          f"{DST.relative_to(ROOT)}")


if __name__ == "__main__":
    if len(sys.argv) != 4:
        sys.exit(__doc__)
    main(*sys.argv[1:])
